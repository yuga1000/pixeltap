export function parseTemplate(template) {
  const rows = template.data.trim().split('\n').map(r => r.trim());
  const height = rows.length;
  const width = rows[0].length;
  const pixels = rows.map(row =>
    [...row].map(ch => {
      if (ch === '.') return null;
      const idx = parseInt(ch, 36);
      return template.palette[idx] || null;
    })
  );
  return { pixels, width, height };
}

export function renderTemplatePreview(template, displaySize = 64) {
  const { pixels, width, height } = parseTemplate(template);
  const canvas = document.createElement('canvas');
  canvas.width = displaySize;
  canvas.height = displaySize;
  const ctx = canvas.getContext('2d');
  const cellW = displaySize / width;
  const cellH = displaySize / height;

  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const px = x * cellW;
      const py = y * cellH;
      ctx.fillStyle = (x + y) % 2 === 0 ? '#2a2a2a' : '#1e1e1e';
      ctx.fillRect(px, py, cellW + 0.5, cellH + 0.5);
      const color = pixels[y][x];
      if (color) {
        ctx.fillStyle = color;
        ctx.fillRect(px, py, cellW + 0.5, cellH + 0.5);
      }
    }
  }
  return canvas;
}

